// ── Core engine ───────────────────────────────────────────────
function clublyGetLang() {
  return localStorage.getItem('clubly_lang') || 'en';
}

function clublySetLang(lang) {
  localStorage.setItem('clubly_lang', lang);
  applyLang(lang);
}
function applyLang(lang) {
  lang = lang || clublyGetLang();
const T = CLUBLY_TRANSLATIONS[lang];
if (!T) return;
if (typeof window !== 'undefined') {
  window.T = T;
  // Update the global T variable in dashboard
  if (typeof window.updateGlobalT === 'function') window.updateGlobalT(T);
  // Re-populate dynamic dropdowns with translated first option
try {
  if (typeof populateMemberShipDropdowns === 'function' && memberShipsData?.length)
    populateMemberShipDropdowns();
  if (typeof populateTrainerActivityOpts === 'function' && activitiesListT?.length)
    populateTrainerActivityOpts();
  if (typeof populateFacilityCatOpts === 'function' && facilityCategories?.length)
    populateFacilityCatOpts();
  if (typeof populateActFacilityOpts === 'function' && facilitiesForAct?.length)
    populateActFacilityOpts();
  if (typeof loadActivitiesForGroups === 'function' && activitiesForGroup?.length)
    loadActivitiesForGroups();
} catch(e) {}
}

  const isAr = lang === 'ar';

  // RTL / LTR
  document.documentElement.lang = lang;
  document.documentElement.dir  = isAr ? 'rtl' : 'ltr';
  
  document.querySelectorAll('.footer-contact, .footer-bottom').forEach(el => {
    el.style.direction = isAr ? 'rtl' : 'ltr';
    el.style.textAlign = isAr ? 'right' : 'left';
  });

  // Apply all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (T[key] !== undefined) el.textContent = T[key];
  });

  // Apply placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (T[key] !== undefined) el.placeholder = T[key];
  });
// Apply titles
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (T[key] !== undefined) el.title = T[key];
  });
  // Update lang toggle button text
  document.querySelectorAll('.clubly-lang-btn').forEach(btn => {
    btn.textContent = isAr ? 'EN' : 'ar';
    btn.setAttribute('title', isAr ? 'Switch to English' : 'التبديل إلى العربية');
  });

  // Fonts
  if (isAr) {
    if (!document.getElementById('clubly-ar-font')) {
      const link = document.createElement('link');
      link.id = 'clubly-ar-font';
      link.rel = 'stylesheet';
      link.href = 'https://fonts.googleapis.com/css2?family=Tajawal:wght@400;500;700;800;900&display=swap';
      document.head.appendChild(link);
    }
    document.body.style.fontFamily = "'Tajawal', 'Cairo', sans-serif";
  } else {
    document.body.style.fontFamily = "'Cairo', sans-serif";
  }

  // ── Re-render JS-generated content ──────────────────
  try {
    // Members table
    if (typeof renderMemberPage === 'function' && typeof filteredMembers !== 'undefined' && filteredMembers.length)
      renderMemberPage(currentPageM);

    // Trainers table
    if (typeof renderTrainerPage === 'function' && typeof filteredTrainers !== 'undefined' && filteredTrainers.length)
      renderTrainerPage(currentPageT);

    // Trainer Ratings
    if (typeof renderRatingsTable === 'function' && typeof _filteredRatings !== 'undefined' && _filteredRatings.length)
      renderRatingsTable();

    // Guests
    if (typeof renderGuestPage === 'function' && typeof _guestsFiltered !== 'undefined' && _guestsFiltered.length)
      renderGuestPage();

    // Contact Messages
    if (typeof renderContactTable === 'function' && typeof _contactFiltered !== 'undefined' && _contactFiltered.length)
      renderContactTable();

    // Bookings
    if (typeof applyAdminBookingFilter === 'function' &&
        typeof _adminAllActivity !== 'undefined' && _adminAllActivity.length)
      applyAdminBookingFilter();

    // Notifications inbox
    if (typeof renderMyNotifList === 'function' && typeof _myNotifsFiltered !== 'undefined' && _myNotifsFiltered.length)
      renderMyNotifList();

    // Notifications history
    if (typeof renderNotifTable === 'function' && typeof notifFiltered !== 'undefined' && notifFiltered.length)
      renderNotifTable();

    // FAQs
    if (typeof renderFaqTable === 'function' && typeof _faqsFiltered !== 'undefined' && _faqsFiltered.length)
      renderFaqTable();

    // Groups
    if (typeof renderGroupTable === 'function' && typeof filteredGroups !== 'undefined' && filteredGroups.length)
      renderGroupTable();

    // Memberships
    if (typeof renderMembershipPage === 'function' && typeof membershipsData !== 'undefined' && membershipsData.length)
      renderMembershipPage(currentPageMs);

    // Facilities
    if (typeof renderFacilityPage === 'function' && typeof filteredFacilities !== 'undefined' && filteredFacilities.length)
      renderFacilityPage(currentPageF);

    // Activities
    if (typeof renderActivityPage === 'function' && typeof filteredActivities !== 'undefined' && filteredActivities.length)
      renderActivityPage(currentPageA);

    // Categories
    if (typeof renderCatPage === 'function' && typeof filteredCats !== 'undefined' && filteredCats.length)
      renderCatPage();

    // Schedule
    if (typeof renderScheduleTable === 'function' && typeof schedulesData !== 'undefined' && schedulesData.length)
      renderScheduleTable();

    // Admins
    if (typeof renderAdmins === 'function' && typeof _admins !== 'undefined' && _admins.length)
      renderAdmins();

    // Bell badge unread count text
// Bell badge unread count text
    if (typeof updateMyNotifUnreadCount === 'function')
      updateMyNotifUnreadCount();

    // Booking modal
    if (typeof window._bpRerender === 'function')
      window._bpRerender();

} catch(e) {
    // silent fail — لو أي function مش موجودة في الصفحة دي
  }
  // Dashboard nav link translation
  const dashLink = document.getElementById('dashboardNavLink');
  if (dashLink) {
    dashLink.innerHTML = `<i class="bi bi-speedometer2 me-1"></i>${T.nav_dashboard || 'Dashboard'}`;
  }
}
// ── Inject lang button into .header-actions ───────────────────
function clublyInjectLangBtn() {
  const actions = document.querySelector('.header-actions');
  if (!actions || document.querySelector('.clubly-lang-btn')) return;

  const btn = document.createElement('button');
 btn.className = 'btn-theme-header clubly-lang-btn';
btn.style.cssText = 'font-size:.8rem;font-weight:700;letter-spacing:.5px;font-family:inherit;';
  const lang = clublyGetLang();
  btn.textContent = lang === 'ar' ? 'EN' : 'عر';
  btn.title = lang === 'ar' ? 'Switch to English' : 'التبديل إلى العربية';
  btn.onclick = () => clublySetLang(clublyGetLang() === 'ar' ? 'en' : 'ar');


const userAvatar = actions.querySelector('.user-avatar, .header-user');
if (userAvatar) {
  const parent = userAvatar.closest('.header-user') || userAvatar;
  actions.insertBefore(btn, parent);
} else {
  const signOutBtn = actions.querySelector('.btn-signout');
  if (signOutBtn) actions.insertBefore(btn, signOutBtn);
  else actions.appendChild(btn);
}
}

